await using (var dbContext = new Context())
{
    var canConnect = await dbContext.Database.CanConnectAsync();
    if (!canConnect)
    {
        Console.WriteLine(@"Error: Connection to database failed");
        Environment.ExitCode = -1;
        return;
    }
}

Console.WriteLine(@"Connection to database successful");

try
{
    var connection = Helper.DbContext.Database.GetDbConnection();
    await connection.OpenAsync();

    // Schema 'dbo' sicherstellen (wird von allen DDL-Skripten vorausgesetzt)
    await using (var schemaCommand = connection.CreateCommand())
    {
        schemaCommand.CommandText = "CREATE SCHEMA IF NOT EXISTS dbo;";
        await schemaCommand.ExecuteNonQueryAsync();
    }

    // Journaltabelle von DbUp anlegen, falls sie noch fehlt (erster Lauf auf leerer DB)
    await using (var command = connection.CreateCommand())
    {
        command.CommandText =
            "SELECT 1 FROM information_schema.tables WHERE table_type='BASE TABLE' AND table_schema='dbo' AND table_name='schemaversions'";
        var result = await command.ExecuteScalarAsync();

        if (result == null)
        {
            command.CommandText =
                "CREATE TABLE dbo.schemaversions (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scriptname varchar(255), applied timestamp);";
            await command.ExecuteNonQueryAsync();
        }
    }

    await connection.CloseAsync();

    if (Helper.ScriptPath == null || !Directory.Exists(Helper.ScriptPath))
    {
        Environment.ExitCode = -1;
        Console.WriteLine(@"Script path missing or not exists");
    }

    if (Environment.ExitCode == -1)
        return;

    // Skripte in Ordner- und Dateireihenfolge ausführen (RelNNNN/ScriptNNNN)
    var directories = Directory.GetDirectories(Helper.ScriptPath!);
    foreach (var folder in directories.OrderBy(d => d.ToString()))
    {
        var files = Directory.GetFiles(folder);
        foreach (var file in files.OrderBy(f => f.ToString()))
        {
            await Helper.ExecuteScript(file.Replace("\\", "/"));
        }
    }

    // MudBlazor-Übersetzungen (MUD_-Schlüssel, Regel des ItreeMudLocalizer) mit den .resx-Dateien abgleichen
    var translationListDe = new List<MudBlazorTranslation>();
    var translationListFr = new List<MudBlazorTranslation>();
    var translationListIt = new List<MudBlazorTranslation>();

    var trlFilePath = @"./Files/MudBlazor/";
    var trlFiles = Directory.GetFiles(trlFilePath);

    foreach (var trlFile in trlFiles)
    {
        if (trlFile.Contains("de-DE"))
            CreateTrslList(trlFile, translationListDe, "de");
        else if (trlFile.Contains("fr-FR"))
            CreateTrslList(trlFile, translationListFr, "fr");
        else if (trlFile.Contains("it-IT"))
            CreateTrslList(trlFile, translationListIt, "it");
    }

    // Mit leerer de-DE-Liste würde der Abgleich unten sämtliche MUD_-Keys aus der DB löschen.
    if (translationListDe.Count == 0)
    {
        throw new Exception($"Keine de-DE-MudBlazor-Übersetzungen unter '{trlFilePath}' gefunden — Abgleich abgebrochen.");
    }

    var counterNewKeys = 0;
    var counterUpdatedKeys = 0;
    var counterDeletedKeys = 0;
    await using (var dbContext = new Context())
    {
        var tTrls = dbContext.Translation.Where(t => t.TrlKey.StartsWith("MUD_")).ToList();
        var relId = await GetReleaseId(dbContext);

        foreach (var trlDe in translationListDe)
        {
            var trlFr = translationListFr.SingleOrDefault(t => t.Key == trlDe.Key);
            var trlIt = translationListIt.SingleOrDefault(t => t.Key == trlDe.Key);

            var tTrl = tTrls.SingleOrDefault(t => t.TrlKey == trlDe.Key);

            if (tTrl == null)
            {
                var newTrl = new Translation
                {
                    TrlId = Guid.NewGuid(),
                    TrlKey = trlDe.Key,
                    TrlDeutsch = trlDe.Deutsch,
                    TrlFranzoesisch = trlFr?.Franzoesisch,
                    TrlItalienisch = trlIt?.Italienisch,
                    TrlRelId = relId
                };
                dbContext.Translation.Add(newTrl);
                counterNewKeys++;
                continue;
            }

            var updated = false;

            if (string.IsNullOrEmpty(tTrl.TrlDeutsch))
            {
                tTrl.TrlDeutsch = trlDe.Deutsch;
                updated = true;
            }
            if (string.IsNullOrEmpty(tTrl.TrlFranzoesisch) && trlFr != null)
            {
                tTrl.TrlFranzoesisch = trlFr.Franzoesisch;
                updated = true;
            }
            if (string.IsNullOrEmpty(tTrl.TrlItalienisch) && trlIt != null)
            {
                tTrl.TrlItalienisch = trlIt.Italienisch;
                updated = true;
            }

            if (updated)
            {
                dbContext.Entry(tTrl).State = EntityState.Modified;
                counterUpdatedKeys++;
            }
        }

        var keyList = translationListDe.Select(t => t.Key).ToList();
        var deletedKeys = tTrls.Where(t => !keyList.Contains(t.TrlKey));

        foreach (var trlToDelete in deletedKeys)
        {
            dbContext.Entry(trlToDelete).State = EntityState.Deleted;
            counterDeletedKeys++;
        }

        dbContext.SaveChanges();

        Console.WriteLine($@"Es wurden: '{counterNewKeys}' neue MudBlazor-Translations hinzugefügt");
        Console.WriteLine($@"Es wurden: '{counterUpdatedKeys}' fehlende MudBlazor-Translations hinzugefügt");
        Console.WriteLine($@"Es wurden: '{counterDeletedKeys}' veraltete MudBlazor-Translations gelöscht");
    }
}
catch (Exception e)
{
    Console.WriteLine(e);
    Environment.ExitCode = -1;
}
async Task<Guid?> GetReleaseId(Context dbContext)
{
    var connection = dbContext.Database.GetDbConnection();

    if (connection.State != System.Data.ConnectionState.Open)
    {
        await connection.OpenAsync();
    }

    try
    {
        using var command = connection.CreateCommand();
        command.CommandText = "SELECT dbo.F_GetLatestReleaseId()";
        var result = await command.ExecuteScalarAsync();

        if (result == null)
            return null;

        var resultString = result.ToString();
        if (string.IsNullOrEmpty(resultString))
            return null;

        return Guid.Parse(resultString);
    }
    finally
    {
        if (connection.State == System.Data.ConnectionState.Open)
        {
            await connection.CloseAsync();
        }
    }
}

void CreateTrslList(string filePath, IList<MudBlazorTranslation> trlList, string language = "de")
{
    var doc = new XmlDocument();
    doc.Load(filePath);
    var rootNode = doc.SelectSingleNode("root");

    var dataNodes = rootNode!.SelectNodes("data");
    foreach (XmlNode dataNode in dataNodes!)
    {
        XmlNode valueNode = dataNode!.SelectSingleNode("value")!;
        var outerXml = dataNode.OuterXml;

        var pattern = @"name=""([^""]*)""";

        var match = Regex.Match(outerXml, pattern);

        if (!match.Success)
        {
            continue;
        }

        var translation = new MudBlazorTranslation
        {
            Key = "MUD_" + match.Groups[1].Value.ToUpper(),
        };

        switch (language)
        {
            case "de":
                translation.Deutsch = valueNode.InnerText;
                break;
            case "fr":
                translation.Franzoesisch = valueNode.InnerText;
                break;
            case "it":
                translation.Italienisch = valueNode.InnerText;
                break;
        }

        trlList.Add(translation);
    }
}

// Wert eines "name=wert"-CLI-Arguments (Name case-insensitiv); null, wenn es nicht angegeben wurde.
static string? ArgValue(string[] args, string name) =>
    args.FirstOrDefault(a => a.ToLower().StartsWith(name))?[name.Length..];

static string MaskConnectionStringPassword(string? connectionString)
{
    if (connectionString == null)
        return "noConnectionString";

    var builder = new DbConnectionStringBuilder
    {
        ConnectionString = connectionString
    };

    if (builder.ContainsKey("Password"))
    {
        builder["Password"] = "***";
    }

    return builder.ConnectionString;
}