var maskedConnectionString = MaskConnectionStringPassword(connString);
Console.WriteLine($@"ConnectionString: {maskedConnectionString}");
Helper.ConnectionString = connString;

var scriptPath = ArgValue(args, "scriptpath=") ?? configuration.GetSection("ScriptPath")["App"];
if (scriptPath == null)
{
    scriptPath = @"./Files/Skripts/";
}
Console.WriteLine($@"ScriptPath: {scriptPath}");
Helper.ScriptPath = scriptPath;

var timeout = ArgValue(args, "commandtimeout=") ?? configuration.GetSection("CommandTimeout").Value;
if (!int.TryParse(timeout, out var commandTimeout))
